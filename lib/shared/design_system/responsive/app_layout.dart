library;

/// Standard layout dimensions used throughout the application.
abstract final class AppLayout {
  const AppLayout._();

  // Maximum content width
  static const double maxContentWidth = 1200;

  // Sidebar
  static const double sidebarWidth = 280;
  static const double collapsedSidebarWidth = 72;

  // Navigation Rail
  static const double navigationRailWidth = 72;

  // Dialog
  static const double dialogMaxWidth = 480;

  // Form
  static const double formMaxWidth = 600;

  // Drawer
  static const double drawerWidth = 320;

  // Dashboard
  static const double dashboardMaxWidth = 1400;
}